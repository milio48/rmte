package main

import (
	"crypto/tls"
	"crypto/x509"
	"log"
	"net/http"
	"os"
	"path/filepath"

	"github.com/gorilla/websocket"
)

// setupTLSConfig ensures valid root CA certificates are available on environments like
// Android, Termux, or minimal containers where /etc/ssl/certs is absent.
func setupTLSConfig(insecure bool) {
	if insecure {
		tlsConfig := &tls.Config{
			InsecureSkipVerify: true,
		}
		websocket.DefaultDialer.TLSClientConfig = tlsConfig
		if t, ok := http.DefaultTransport.(*http.Transport); ok {
			t.TLSClientConfig = tlsConfig
		}
		return
	}

	pool, err := x509.SystemCertPool()
	if err != nil || pool == nil {
		pool = x509.NewCertPool()
	}

	// 1. Termux & common Linux CA file locations
	candidates := []string{
		os.Getenv("SSL_CERT_FILE"),
		filepath.Join(os.Getenv("PREFIX"), "etc/tls/cert.pem"),
		filepath.Join(os.Getenv("PREFIX"), "etc/ssl/certs/ca-certificates.crt"),
		"/data/data/com.termux/files/usr/etc/tls/cert.pem",
		"/data/data/com.termux/files/usr/etc/ssl/certs/ca-certificates.crt",
		"/etc/ssl/certs/ca-certificates.crt",
		"/etc/pki/tls/certs/ca-bundle.crt",
		"/etc/ssl/ca-bundle.pem",
		"/etc/ssl/cert.pem",
	}
	for _, p := range candidates {
		if p == "" {
			continue
		}
		if data, err := os.ReadFile(p); err == nil && len(data) > 0 {
			pool.AppendCertsFromPEM(data)
		}
	}

	// 2. Android system cert directories (Android 14+ APEX, /system/etc/security/cacerts)
	caDirs := []string{
		os.Getenv("SSL_CERT_DIR"),
		"/apex/com.android.conscrypt/cacerts",
		"/system/etc/security/cacerts",
	}
	for _, dir := range caDirs {
		if dir == "" {
			continue
		}
		if entries, err := os.ReadDir(dir); err == nil {
			for _, entry := range entries {
				if !entry.IsDir() {
					if data, err := os.ReadFile(filepath.Join(dir, entry.Name())); err == nil {
						pool.AppendCertsFromPEM(data)
					}
				}
			}
		}
	}

	// 3. Embedded trusted root CAs (Let's Encrypt ISRG Root X1/X2, Google Trust Services R1/R2, DigiCert)
	if !pool.AppendCertsFromPEM([]byte(embeddedRootCAs)) {
		log.Println("[TLS] Warning: failed to parse embedded root CA bundle")
	}

	tlsConfig := &tls.Config{
		RootCAs: pool,
	}
	websocket.DefaultDialer.TLSClientConfig = tlsConfig
	if t, ok := http.DefaultTransport.(*http.Transport); ok {
		t.TLSClientConfig = tlsConfig
	}
}

